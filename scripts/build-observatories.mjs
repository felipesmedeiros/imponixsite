import { build } from 'vite';
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { resolve, extname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.png': 'image/png', '.jpg': 'image/jpeg', '.otf': 'font/otf', '.svg': 'image/svg+xml' };
export async function buildObservatories() {
  const assets = {};
  for (const slug of ['gsc', 'noema', 'photoncytosis']) {
    const appRoot = resolve(root, 'observatory/vendor', slug);
    const outDir = resolve(root, '.observatory-build', slug);
    await build({ configFile: false, root: appRoot, base: `/observatory/${slug}/`, logLevel: 'warn', build: { outDir, emptyOutDir: true, sourcemap: false } });
    async function collect(folder) {
      for (const file of await readdir(folder, { withFileTypes: true })) {
        const path = resolve(folder, file.name);
        if (file.isDirectory()) { await collect(path); continue; }
        const key = `/observatory/${slug}/${relative(outDir, path).replaceAll('\\', '/')}`;
        let bytes = await readFile(path);
        if (file.name === 'index.html') {
          const bridge = '<script src="/observatory/bridge.js"></script>';
          bytes = Buffer.from(bytes.toString().replace('<head>', `<head>${bridge}<meta name="robots" content="noindex,nofollow,noarchive">`).replace('<body>', '<body><a href="/observatory/" style="position:fixed;bottom:12px;right:12px;z-index:9999;background:#171b25;color:white;padding:10px 16px;border:1px solid #697080;border-radius:5px;font:13px system-ui;text-decoration:none">← All observatories</a>'));
        }
        assets[key] = [types[extname(path)] || 'application/octet-stream', bytes.toString('base64')];
      }
    }
    await collect(outDir);
  }
  for (const name of ['hub.html', 'hub.css', 'bridge.js']) {
    const bytes = await readFile(resolve(root, 'observatory', name));
    assets[`/observatory/${name}`] = [types[extname(name)], bytes.toString('base64')];
  }
  await mkdir(resolve(root, 'observatory/generated'), { recursive: true });
  await writeFile(resolve(root, 'observatory/generated/assets.mjs'), `// Generated by build-observatories.mjs; contains no histories.\nexport default ${JSON.stringify(assets)};\n`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildObservatories();
